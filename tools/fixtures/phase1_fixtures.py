"""Write the Phase 1 (Dipolar Studio 0.1) fixtures that V1.3's D-1 gate tests use.

**Run this only on 0.1 code** (it was run once, on commit a448ca8, the last commit before V1.3
changed the numerical context and the project schema). Its outputs are committed under
``packages/dipolar-app/tests/data/phase1/`` and are never regenerated by later code:

- ``journal-only/``: a project directory with a journal and a run blob, no snapshot;
- ``snapshot-journal/``: the same history compacted into a snapshot, followed by more records;
- ``export-v2.dipolar.json``: an imported project with couplings, exported by 0.1 (schema 2);
- ``export-v1.dipolar.json``: the same project hand-converted to schema 1 (the order rename does not
  apply to imported geometry; schema 1 has no ``next_coupling_id``).

Usage: ``uv run python tools/fixtures/phase1_fixtures.py <output-dir>``.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from dipolar_app.api import Studio

CSV = "spin_a,spin_b,D_obs_Hz,sigma_Hz\nH3,H4,-1500.0,2.0\nH3,H6,310.0,1.5\nH4,H7,-120.0,1.0\n"


def history(studio: Studio) -> None:
    studio.call("project.open_example", name="biphenyl-synthetic", expected_science_revision=0)
    studio.call(
        "model.set",
        kind="jump4",
        order="bisector-diagonal",
        frame="bisector",
        phi_domain=[{"value": 0.0, "unit": "deg"}, {"value": 90.0, "unit": "deg"}],
        expected_science_revision=1,
    )
    studio.fit()
    studio.call("view.select", ids=["cpl_000001"])


def main(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=False)
    journal_only = out / "journal-only"
    with Studio.local(journal_only) as studio:
        history(studio)
    (journal_only / "serve.lock").unlink()

    snap = out / "snapshot-journal"
    with Studio.local(snap) as studio:
        history(studio)
        studio._transport._session.compact()  # type: ignore[attr-defined]
        studio.call("history.undo", expected_science_revision=studio.science_revision)
    (snap / "serve.lock").unlink()

    from dipolar_app.science_ops import ETHANE_XYZ

    with Studio.local() as studio:
        studio.call("project.import_xyz", xyz=ETHANE_XYZ, name="ethane", expected_science_revision=0)
        mapping = studio.call("couplings.reconcile", csv=CSV)["proposed_mapping"]
        studio.call("couplings.import", csv=CSV, confirmed_mapping=mapping, expected_science_revision=1)
        text = studio.call("project.export")["text"]
    (out / "export-v2.dipolar.json").write_text(text, encoding="utf-8")
    document = json.loads(text)
    project = document["project"]
    del project["next_coupling_id"]
    project["schema_version"] = 1
    document["schema_version"] = 1
    (out / "export-v1.dipolar.json").write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    for leftover in out.rglob("__pycache__"):
        shutil.rmtree(leftover)


if __name__ == "__main__":
    main(Path(sys.argv[1]))
